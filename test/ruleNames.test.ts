import { describe, expect, it } from 'vitest';
import { getRuleNames, removeRuleNameSentences } from '../src/domain/ruleNames';
import type { CardData } from '../src/domain/types';

const card: CardData = {
  id: 'c:example', custom: true, name: '検証用', kind: 'monster', monsterTypes: [], text: '',
};

describe('手札で効くルール上の名前', () => {
  it.each([
    ['白き竜の落胤', 'このカード名はルール上「アルバスの落胤」として扱う。', 'アルバスの落胤'],
    ['ハーピィ・レディ・ＳＢ', 'このカード名はルール上「ハーピィ・レディ」として扱う。', 'ハーピィ・レディ'],
    ['置換融合', 'このカードのカード名はルール上「融合」として扱う。', '融合'],
    ['ハーピィ・レディ１', 'このカードのカード名は「ハーピィ・レディ」として扱う。', 'ハーピィ・レディ'],
    ['破滅の天使ルイン', '①：このカードのカード名は、手札・フィールドに存在する限り「破滅の女神ルイン」として扱う。', '破滅の女神ルイン'],
    ['終焉の悪魔デミス', '①：このカードのカード名は、手札・フィールドに存在する限り「終焉の王デミス」として扱う。', '終焉の王デミス'],
    ['破滅の美神ルイン', '①：このカードのカード名は、手札・フィールドに存在する限り「破滅の女神ルイン」として扱う。', '破滅の女神ルイン'],
    ['終焉の覇王デミス', '①：このカードのカード名は、手札・フィールドに存在する限り「終焉の王デミス」として扱う。', '終焉の王デミス'],
    ['赤しゃりの軍貫', '①：このカードのカード名は、手札・デッキ・フィールド・墓地に存在する限り「しゃりの軍貫」として扱う。', 'しゃりの軍貫'],
    ['霊魂鳥影－姫孔雀', '①：このカードのカード名は、手札・フィールドに存在する限り「霊魂鳥神－姫孔雀」として扱う。', '霊魂鳥神－姫孔雀'],
    ['霊魂鳥影－彦孔雀', '①：このカードのカード名は、手札・フィールドに存在する限り「霊魂鳥神－彦孔雀」として扱う。', '霊魂鳥神－彦孔雀'],
    ['破滅と終焉の支配者', '①：このカードのカード名は、手札・フィールドに存在する限り「終焉の王デミス」として扱う。', '終焉の王デミス'],
  ])('%s の実データの宣言を読む', (name, text, expected) => {
    expect(getRuleNames({ ...card, name, text })).toEqual([expected]);
    expect(getRuleNames({ ...card, name, text: '', pendulumText: text })).toEqual([expected]);
    expect(removeRuleNameSentences(text)).toBe('');
  });

  it.each([
    ['ハーピィ・クィーン', '①：このカードのカード名は、フィールド・墓地に存在する限り「ハーピィ・レディ」として扱う。'],
    ['ワイト夫人', 'このカードのカード名は、墓地に存在する限り「ワイト」として扱う。'],
    ['プロト・サイバー・ドラゴン', 'このカードのカード名は、フィールド上に表側表示で存在する限り「サイバー・ドラゴン」として扱う。'],
    ['魔知ガエル', '①：このカードはモンスターゾーンに存在する限り、カード名を「デスガエル」として扱う。'],
    ['スペア・ジェネクス', 'このカードのカード名はエンドフェイズまで「ジェネクス・コントローラー」として扱う。'],
    ['真紅眼融合', 'この効果で特殊召喚したモンスターのカード名は「真紅眼の黒竜」として扱う。'],
    ['紋章の明滅', 'そのモンスターのカード名を「アンノウン」として扱う。'],
    ['闇に堕ちた天使', 'このカード名はルール上「堕天使」カードとしても扱う。'],
    ['ティマイオスの眼', 'このカード名はルール上「伝説の竜 ティマイオス」としても扱う。'],
    ['クリティウスの牙', 'このカードのカード名はルール上「伝説の竜 クリティウス」としても扱う。'],
    ['忘却の海底神殿', 'このカードがフィールド上に存在する限り、このカードのカード名は「海」として扱う。'],
  ])('%s の実データの文は宣言として読まず残す', (name, text) => {
    expect(getRuleNames({ ...card, name, text })).toEqual([]);
    expect(removeRuleNameSentences(text)).toBe(text);
  });

  it.each([
    'このカードのカード名は、手札以外・フィールドに存在する限り「別名」として扱う。',
    'このカードのカード名は、相手の手札に存在する限り「別名」として扱う。',
    '条件を満たす場合、このカード名はルール上「別名」として扱う。',
    'このカード名はルール上「別名」として扱う場合がある。',
    'このカード名はルール上「別名」として扱う',
    'このカード名は「別名」として扱う。',
    'このカード名はルール上「別」名」として扱う。',
  ])('指定の文全体と一致しない文を読まない: %s', text => {
    expect(getRuleNames({ ...card, text })).toEqual([]);
    expect(removeRuleNameSentences(text)).toBe(text);
  });

  it.each(['', '①：', '①:', '⑳：', '●', '　● ⑳: ①：●　'])('前置き「%s」と前後の空白を除く', prefix => {
    const text = `　${prefix}このカード名はルール上「 Ａ・Ｂ 」として扱う。　`;
    expect(getRuleNames({ ...card, text })).toEqual([' Ａ・Ｂ ']);
    expect(removeRuleNameSentences(text).trim()).toBe('');
  });

  it('句点と改行で分け、両効果欄の名前を出現順に重複なくキャッシュする', () => {
    const target = {
      ...card,
      text: '通常の効果。①：このカード名はルール上「Ｂ」として扱う。\r\n'
        + 'このカードのカード名は「Ａ」として扱う。\nこのカード名はルール上「Ｂ」として扱う。',
      pendulumText: 'このカード名はルール上「Ａ」として扱う。\rこのカード名はルール上「Ｃ」として扱う。',
    };
    const result = getRuleNames(target);
    expect(result).toEqual(['Ｂ', 'Ａ', 'Ｃ']);
    expect(getRuleNames(target)).toBe(result);
    expect(getRuleNames({ ...target })).toEqual(result);
    expect(getRuleNames({ ...target })).not.toBe(result);
    expect(getRuleNames(card)).toBe(getRuleNames(card));
  });

  it('改行で区切られた不完全な宣言と効果欄をまたぐ宣言は結合しない', () => {
    expect(getRuleNames({ ...card, text: 'このカード名はルール上\n「別名」として扱う。' })).toEqual([]);
    expect(getRuleNames({ ...card, text: 'このカード名はルール上', pendulumText: '「別名」として扱う。' })).toEqual([]);
    expect(removeRuleNameSentences('残す文\nこのカード名はルール上「別名」として扱う。\n後の文。'))
      .toBe('残す文\n後の文。');
  });
});
